# Let's test what an improved HeuristicExtractor would extract
PREDICATE_RULES = [
    # (pattern, predicate, is_passive)
    (r"\b(?:uses|utilizes|employs|applies|adopts)\b", "USES", False),
    (r"\b(?:is based on|builds upon|extends|derives from)\b", "EXTENDS", False),
    (r"\b(?:implements|implemented|incorporates)\b", "IMPLEMENTS", False),
    (r"\b(?:integrates with|connects to|interacts with|links to|interfaces with)\b", "INTERACTS_WITH", False),
    (r"\b(?:enables|supports|facilitates|provides|powers)\b", "ENABLES", False),
    (r"\b(?:stores|indexes|persists|contains|houses)\b", "CONTAINS", False),
    (r"\b(?:extracts|parses|ingests|retrieves)\b", "EXTRACTS", False),
    (r"\b(?:generates|produces|creates|constructs)\b", "GENERATES", False),
    (r"\b(?:requires|depends on|relies on)\b", "REQUIRES", False),
    (r"\b(?:outperforms|improves|enhances)\b", "IMPROVES", False),
    (r"\b(?:evaluates|measures|benchmarks)\b", "EVALUATES", False),
    (r"\b(?:trained on|trains on|fine-tuned on)\b", "TRAINED_ON", False),
    (r"\b(?:causes|leads to|results in)\b", "CAUSES", False),
    (r"\b(?:is part of|belongs to|consists of|composed of)\b", "PART_OF", False),
    # Passive
    (r"\b(?:developed by|created by|built by|authored by)\b", "DEVELOPED_BY", True),
    (r"\b(?:used by|utilized by|employed by)\b", "USES", True),
    (r"\b(?:enabled by|powered by|supported by)\b", "ENABLES", True),
    (r"\b(?:extracted by|parsed by|ingested by)\b", "EXTRACTS", True),
    (r"\b(?:generated by|produced by)\b", "GENERATES", True),
]

def extract_improved(text, entity_names_dict):
    rels = []
    sentences = re.split(r"(?<=[.!?])\s+", text)
    for sent in sentences:
        sent_clean = sent.strip()
        if not sent_clean:
            continue
        sent_lower = sent_clean.lower()
        spans = []
        for norm_name, (can_name, eid, etype) in entity_names_dict.items():
            for m in re.finditer(rf"\b{re.escape(norm_name)}\b", sent_lower):
                spans.append((m.start(), m.end(), can_name, eid))
        spans.sort(key=lambda x: x[0])
        
        # Deduplicate overlapping spans (keep longer)
        non_overlapping = []
        for s in spans:
            if not non_overlapping:
                non_overlapping.append(s)
            else:
                last = non_overlapping[-1]
                if s[0] < last[1]: # overlap
                    if (s[1] - s[0]) > (last[1] - last[0]):
                        non_overlapping[-1] = s
                else:
                    non_overlapping.append(s)
        
        # Pairwise search
        for i in range(len(non_overlapping)):
            for j in range(i + 1, min(i + 4, len(non_overlapping))):
                e1 = non_overlapping[i]
                e2 = non_overlapping[j]
                if e1[3] == e2[3]:
                    continue
                between = sent_clean[e1[1]:e2[0]].strip().lower()
                matched_rule = None
                for pat, pred, is_passive in PREDICATE_RULES:
                    if re.search(pat, between, re.IGNORECASE):
                        matched_rule = (pred, is_passive)
                        break
                if not matched_rule:
                    # Also check sentence clause surrounding both
                    clause = sent_clean[max(0, e1[0] - 20): min(len(sent_clean), e2[1] + 20)].lower()
                    for pat, pred, is_passive in PREDICATE_RULES:
                        if re.search(pat, clause, re.IGNORECASE):
                            matched_rule = (pred, is_passive)
                            break
                if matched_rule:
                    pred, is_passive = matched_rule
                    subj = e2[3] if is_passive else e1[3]
                    obj = e1[3] if is_passive else e2[3]
                    subj_name = e2[2] if is_passive else e1[2]
                    obj_name = e1[2] if is_passive else e2[2]
                    rels.append((subj_name, pred, obj_name, sent_clean))
    return rels

ingestion = DocumentIngestionService()
chunks = ingestion.chunk_text(sample_text_1 + "\n" + sample_text_2, source_filename="test.txt")
extractor = EntityExtractor(mode="heuristic")
res = extractor.extract_from_chunks(chunks)

# Build entity lookup from res
entity_names_dict = {}
for eid, ent in res.entities.items():
    entity_names_dict[ent.name.lower()] = (ent.name, eid, ent.entity_type)
    for a in ent.aliases:
        entity_names_dict[a.lower()] = (ent.name, eid, ent.entity_type)

rels = extract_improved(sample_text_1 + "\n" + sample_text_2, entity_names_dict)
print(f"Total extracted relationships: {len(rels)}")
for s, p, o, ev in rels:
    print(f"  {s} --[{p}]--> {o}")
